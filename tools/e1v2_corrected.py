"""Generate the corrected exploratory replay, its intervals and the principal paper table.

No calls to a model. Historical results under results/e1v2 are never overwritten.
    python tools/e1v2_corrected.py --out results/e1v2_corrected
    Add --table ../mdpi-paper/tables/e1-corrected.tex to regenerate the manuscript table.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from e1v2_clustered import DRAWS, MODELS, NAMES, SEED, clustered, paired

from dsoi.experiments.e1v2_corrected import ARMS, score
from dsoi.experiments.e1v2_notices import load
from dsoi.experiments.e1v2_run import load_replies

ROOT = Path(__file__).resolve().parents[1]


def summarize(rows: list[dict], margins: dict) -> dict:
    rng = np.random.default_rng(SEED)
    result = {"post_hoc": True, "fresh_model_calls": 0, "margin_q": margins,
              "interval_method": "approximate case-clustered Wilson; paired case bootstrap",
              "seed": SEED, "draws": DRAWS, "models": {}}
    for model in sorted(margins):
        test = [r for r in rows if r["model"] == model and r["split"] == "test"]
        change = [r for r in test if r["expect"] == "change"]
        quiet = [r for r in test if r["expect"] != "change"]

        def rate(sub, key):
            return clustered([(r["case_id"], bool(r[key])) for r in sub], rng)

        data = {"change_rows": len(change), "quiet_rows": len(quiet),
                "snapshot_mismatches": sum(not r["snapshot_ok"] for r in test),
                "abstained": rate(change, "abstained"),
                "emitted_coverage": rate(change, "emitted_covered"),
                "coverage_stated": rate(change, "covered_stated"),
                "coverage_calibrated": rate(change, "covered_calibrated"),
                "scope_exact": rate(change, "scope_exact"),
                "quiet_ok": rate(quiet, "quiet_ok"),
                "held_quiet": rate(quiet, "abstained"), "arms": {}, "differences": {}}
        for arm in ARMS:
            releases = [r for r in change if r[f"released_{arm}"]]
            feasible = [r[f"excess_{arm}"] for r in releases if not r[f"violation_{arm}"]]
            data["arms"][arm] = {
                "release": rate(change, f"released_{arm}"),
                "error": rate(change, f"error_{arm}"),
                "violation": rate(change, f"violation_{arm}"),
                "violation_given_release": rate(releases, f"violation_{arm}"),
                "feasible_releases": len(feasible),
                "mean_cost_feasible": float(np.mean(feasible)) if feasible else None}
        keys = [(model, r["case_id"], r["repeat"]) for r in change]
        for a, b in (("stated", "point"), ("calibrated", "stated"),
                     ("stated_hold", "stated"), ("recheck", "stated")):
            data["differences"][f"{a} - {b}"] = paired(
                {k: r[f"violation_{a}"] for k, r in zip(keys, change, strict=True)},
                {k: r[f"violation_{b}"] for k, r in zip(keys, change, strict=True)}, keys, rng)
        result["models"][model] = data
    return result


def pct(value: dict | None) -> str:
    if value is None:
        return "--"
    lo, hi = value["ci95"]
    return f"{100 * value['rate']:.0f} ({100 * lo:.0f}--{100 * hi:.0f})"


def table(result: dict) -> str:
    lines = ["%% Generated by tools/e1v2_corrected.py; exploratory stored-reply replay.",
             r"\begin{table}[t]", r"\begin{adjustwidth}{-\extralength}{0cm}",
             r"\centering\footnotesize",
             r"\caption{Corrected exploratory replay of stored replies (Section~\ref{sec:e1}); "
             r"no fresh model calls. Each model has 176 change-notice and 48 quiet-notice "
             r"case-repeats. Rates in percent with approximate 95\% case-clustered intervals "
             r"(Appendix~\ref{app:supp}). The source-priority and widening defects are corrected "
             r"together; Table~\ref{tab:e1factorial} separates them. The fitted margin is a "
             r"descriptive heuristic, not a validated conformal "
             r"guarantee. Cost is reported only for feasible releases, with their count. The "
             r"historical defective arms are retained in the artifact. (a)~Interpretation and "
             r"resolved state over change notices. (b)~Decisions per gate over change notices."
             r"}\label{tab:e1corrected}",
             r"\textit{(a) Interpretation and resolved state}\par\smallskip",
             r"\begin{tabular}{@{}lrrrrr@{}}\toprule",
             r"Model & Abstained & Emitted coverage & State coverage & Widened coverage & $q$"
             r"\\\midrule"]
    for model in MODELS:
        data = result["models"][model]
        lines.append(f"{NAMES[model]} & {pct(data['abstained'])} & "
                     f"{pct(data['emitted_coverage'])} & {pct(data['coverage_stated'])} & "
                     f"{pct(data['coverage_calibrated'])} & {result['margin_q'][model]:g}"
                     r"\\")
    lines += [r"\bottomrule\end{tabular}\par\medskip",
              r"\textit{(b) Decisions per gate}\par\smallskip",
              r"\begin{tabular}{@{}llrrrrr@{}}\toprule",
              r"Model & Arm & Released & $\Pr[V]$ & $\Pr[V\mid R]$ & Feasible cost & $n$"
              r"\\\midrule"]
    labels = {"point": "nominal", "stated": "stated box", "calibrated": "widened box",
              "recheck": "recheck", "stated_hold": "stated box, hold"}
    for model in MODELS:
        data = result["models"][model]
        for i, arm in enumerate(ARMS):
            values = data["arms"][arm]
            cost = values["mean_cost_feasible"]
            lines.append(f"{NAMES[model] if i == 0 else ''} & {labels[arm]} & "
                         f"{pct(values['release'])} & {pct(values['violation'])} & "
                         f"{pct(values['violation_given_release'])} & "
                         f"{'--' if cost is None else f'{cost:.0f}'} & "
                         f"{values['feasible_releases']}" + r"\\")
        lines.append(r"\addlinespace")
    lines += [r"\bottomrule\end{tabular}", r"\end{adjustwidth}", r"\end{table}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=ROOT / "results/e1v2_corrected")
    ap.add_argument("--table", type=Path)
    ap.add_argument("--cases", type=Path, default=ROOT / "data/e1v2/cases.jsonl")
    ap.add_argument("--replies", type=Path, default=ROOT / "results/e1v2/replies.jsonl")
    args = ap.parse_args(argv)
    cases, replies = args.cases, args.replies
    rows, margins = score(load(cases), load_replies(replies), 0.1, args.out)
    result = summarize(rows, margins)
    result["inputs_sha256"] = {name: hashlib.sha256(path.read_bytes()).hexdigest()
                                for name, path in (("cases", cases), ("replies", replies))}
    (args.out / "summary.json").write_text(json.dumps(result, indent=1, sort_keys=True) + "\n")
    if args.table:
        args.table.write_text(table(result))
    print(json.dumps({m: {"q": margins[m],
                         "coverage": s["coverage_stated"]["k"],
                         "stated_violations": s["arms"]["stated"]["violation"]["k"],
                         "widened_violations": s["arms"]["calibrated"]["violation"]["k"]}
                      for m, s in result["models"].items()}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
