"""Where the corrected replay's violations come from (post hoc, 15 Nov 2026; no model calls).

    python tools/e1v2_violation_sources.py \
        [--table ../manuscripts/arxiv-paper/tables/e1-violation-sources.tex]

Reads results/e1v2_corrected/rows.csv (tools/e1v2_corrected.py) and sorts every change-notice
case-repeat of the test part into one class, in the order of Table e1fail: the model declined
a message; only L1's contract rejected one; the cycle ended in an error and executed
nothing; the reading named the wrong plant, the wrong weeks
of plant X, or intervals that miss the true capacity; the emitted intervals covered the truth
but the state the planner read did not (information lost after interpretation); or the state
covered the truth. For each class it counts the case-repeats whose plan under the stated box
gate violated the true capacity. After an abstention or a rejection the previous state stands
(Definition 3), so a violation there comes from keeping that state, not from a wrong reading.
Writes results/e1v2_violation_sources.json.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ("qwen2.5:7b-instruct", "llama3.1:8b", "phi4:latest")
NAMES = {"qwen2.5:7b-instruct": "Qwen2.5 7B", "llama3.1:8b": "Llama 3.1 8B",
         "phi4:latest": "Phi-4 14B"}
CLASSES = (("model", "Model abstained, old state kept"),
           ("contract", "L1 rejected, old state kept"),
           ("error", "Error cycle, nothing executed"),
           ("entity", "Wrong plant"),
           ("scope", "Wrong weeks"),
           ("value", "Intervals miss the truth"),
           ("lost", "Lost after interpretation"),
           ("covered", "State read covers the truth"))


def _b(v: str) -> bool:
    return v == "True"


def classify(r: dict) -> str:
    if int(r["model_abstentions"]) > 0:
        return "model"
    if int(r["contract_rejections"]) > 0:
        return "contract"
    if _b(r["error_stated"]):
        return "error"
    if not _b(r["entity_ok"]):
        return "entity"
    if not _b(r["scope_exact"]):
        return "scope"
    if not _b(r["emitted_covered"]):
        return "value"
    if not _b(r["covered_stated"]):
        return "lost"
    return "covered"


def analyse(rows: list[dict]) -> dict:
    out = {"post_hoc": True, "fresh_model_calls": 0, "gate": "stated box", "models": {}}
    for m in MODELS:
        rs = [r for r in rows if r["model"] == m and r["split"] == "test"
              and r["expect"] == "change"]
        res = {c: {"case_repeats": 0, "violated": 0} for c, _ in CLASSES}
        for r in rs:
            c = classify(r)
            res[c]["case_repeats"] += 1
            res[c]["violated"] += _b(r["violation_stated"])
        v = sum(x["violated"] for x in res.values())
        assert v == sum(_b(r["violation_stated"]) for r in rs)
        assert res["covered"]["violated"] == 0, "the box gate violated with a covering state"
        out["models"][m] = {"case_repeats": len(rs), "violated": v,
                            "violated_after_abstention": res["model"]["violated"]
                            + res["contract"]["violated"], "classes": res}
    return out


def table(res: dict) -> str:
    n = res["models"][MODELS[0]]["case_repeats"]
    lines = [
        "%% Generated by replication-package/tools/e1v2_violation_sources.py (post hoc); "
        "do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering\footnotesize\setlength{\tabcolsep}{3pt}",
        r"\caption{\cdraft{Where the corrected replay's violations come from (test part, "
        f"{n} change-notice case-repeats per model; no fresh model calls). Each case-repeat is "
        r"counted once, in the order listed, as in Table~\ref{tab:e1fail}; each cell gives "
        r"case-repeats / those whose plan violated the true capacity under the stated box gate "
        r"(Table~\ref{tab:e1corrected}). Lost after interpretation: the emitted intervals "
        r"cover the truth but the state the planner read does not. After an abstention or a "
        r"contract rejection the "
        r"previous state stands (Definition~\ref{def:delta}), so those violations come from "
        r"keeping it, not from a wrong reading.}}\label{tab:e1violsrc}",
        r"\begin{tabular}{@{}lrrr@{}}",
        r"\toprule",
        "Outcome & " + " & ".join(NAMES[m] for m in MODELS) + r"\\\midrule",
    ]
    for c, label in CLASSES:
        lines.append(label + " & " + " & ".join(
            "{} / {}".format(res["models"][m]["classes"][c]["case_repeats"],
                             res["models"][m]["classes"][c]["violated"]) for m in MODELS) + r"\\")
    lines.append(r"\midrule")
    lines.append("All & " + " & ".join(
        "{} / {}".format(res["models"][m]["case_repeats"], res["models"][m]["violated"])
        for m in MODELS) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rows", type=Path, default=ROOT / "results/e1v2_corrected/rows.csv")
    ap.add_argument("--out", type=Path, default=ROOT / "results/e1v2_violation_sources.json")
    ap.add_argument("--table", type=Path)
    args = ap.parse_args(argv)
    res = analyse(list(csv.DictReader(open(args.rows, newline=""))))
    args.out.write_text(json.dumps(res, indent=1, sort_keys=True) + "\n")
    if args.table:
        args.table.write_text(table(res))
    for m in MODELS:
        x = res["models"][m]
        print(NAMES[m], x["violated"], "violations,", x["violated_after_abstention"],
              "after an abstention or rejection")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
