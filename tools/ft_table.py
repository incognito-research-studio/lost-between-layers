"""Table of the fault-injection evaluation for the paper (Table "faulttrial").

    uv run python tools/ft_table.py --out faulttrial.tex

Reads only the stored scores of the three analyses, each written by the frozen
`tools/ft_score.py`: round 1 frozen (results/fault_trial_v2_scores.json), round 1 with the
extended effect trace of deviation 1 (results/fault_trial_v2_reanalysis_scores.json) and
round 2 (results/fault_trial_r2_scores.json). It computes nothing new; it formats the counts,
the Wilson intervals (as percentages, rounded half up) and the exact McNemar p-values.
Written 9 Nov 2026, after both rounds were scored; the frozen instruments are not changed.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLUMNS = (
    ("Round 1, frozen", "results/fault_trial_v2_scores.json"),
    ("Round 1, extended trace", "results/fault_trial_v2_reanalysis_scores.json"),
    ("Round 2", "results/fault_trial_r2_scores.json"),
)

CAPTION = (
    r"\caption{\cdraft{Fault-injection evaluation with separated roles. Faults "
    r"detected by each nested configuration among the effective faults, with 95\% "
    r"Wilson intervals in percent; the unit is the fault. Round 1's primary result is "
    r"the frozen analysis; its secondary analysis extends the effect trace to replay "
    r"and reloaded-log outputs, a deviation decided after unblinding. Round 2 used the "
    r"extended trace from the start, with the same checks. Localized: the firing "
    r"checks name the layer the generator patched. Silent: faults with at least one "
    r"run that has more violations of the true constraints than the clean run while no "
    r"check of the configuration newly fires.}}\label{tab:fault}"
)

HEAD = (r"""%% Fault-injection evaluation with separated roles (9 Nov 2026).
%% Generated by replication-package/tools/ft_table.py from results/fault_trial_v2_scores.json
%% (round 1, frozen), fault_trial_v2_reanalysis_scores.json (round 1, deviation 1) and
%% fault_trial_r2_scores.json (round 2). Do not edit by hand.
\begin{table}[t]
\begin{adjustwidth}{-\extralength}{0cm}
\centering\footnotesize
""" + CAPTION + "\n" + r"""\renewcommand{\arraystretch}{1.1}
\begin{tabular}{@{}lccc@{}}
\toprule
""")
TAIL = r"""\bottomrule
\end{tabular}
\end{adjustwidth}
\end{table}
"""


def pct(x: float) -> int:
    return math.floor(x * 100 + 0.5 + 1e-9)


def detected(cfg: dict) -> str:
    lo, hi = cfg["wilson95"]
    return f"{cfg['detected']} ({pct(max(lo, 0.0))}--{pct(hi)})"


def pval(p: float) -> str:
    return f"{p:.2g}" if p < 0.01 else f"{p:.3f}"


def cells(d: dict) -> dict[str, str]:
    c = d["configs"]
    negs = d["negatives"]
    alarms = max(negs[k]["false_alarms"] for k in ("solver", "generic", "full"))
    return {
        "Patches written / effective": f"{d['faults_total']} / {d['status']['effective']}",
        "Detected, solver": detected(c["solver"]),
        "Detected, generic": detected(c["generic"]),
        "Detected, full": detected(c["full"]),
        r"\quad of which before execution": str(c["full"]["detected_pre_execution"]),
        r"\quad of which localized": str(c["full"]["localized"]),
        "Silent, full / generic": (f"{c['full']['faults_with_silent_violations']} / "
                                   f"{c['generic']['faults_with_silent_violations']}"),
        "Exact McNemar $p$, full vs generic": pval(d["mcnemar"]["generic_vs_full"]["p_exact"]),
        f"False alarms on {negs['n']} negative cases, any configuration": str(alarms),
    }


def table() -> str:
    cols = [cells(json.loads((ROOT / path).read_text())) for _, path in COLUMNS]
    names = " & ".join(rf"\cdraft{{{name}}}" for name, _ in COLUMNS)
    out = [HEAD, " & " + names + r"\\\midrule" + "\n"]
    for row in cols[0]:
        vals = " & ".join(rf"\cdraft{{{c[row]}}}" for c in cols)
        out.append(rf"\cdraft{{{row}}} & {vals}\\" + "\n")
    out.append(TAIL)
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.write_text(table())


if __name__ == "__main__":
    main()
