"""Table tab:layaconf from results/laya_conformance.json (no model calls).

    python tools/laya_table.py --out laya-conformance.tex

Presentation only, written after the frozen run (data/laya/DEVIATIONS.md, entry 1): it replaces
the `table` step of the frozen tools/laya_conformance.py, which pooled the change and no-change
notices in the retention rows and printed a one-value range as "20 to 20". No measure changes.

16 Nov 2026: with --baselines (results/laya_baselines.json, written by tools/laya_baselines.py),
the table also prints the post hoc reference points logged in data/laya/DEVIATIONS.md
("Post hoc analyses", entry 1), each row marked with a dagger.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _frac(a, b) -> str:
    return f"{a}/{b}"


def table(r: dict, b: dict | None = None) -> str:
    n, inv, by = r["cases"], r["invariance"], r["by_expect"]
    ch, nc, ab = by["change"], by["no_change"], by["abstain"]
    sh = [inv[k]["flips"] for k in inv if k.startswith("shuffle")]
    w = r["wide56"]
    lo, hi = w["distinct_min"], w["distinct_max"]
    kept = f"{lo} of {w['options']}" if lo == hi else f"{lo} to {hi} of {w['options']}"
    g = r["cpu_vs_mps"]
    rows = [
        ("Repeat on CPU: identical probabilities", _frac(r["repeat_cpu"]["identical_replies"], n)),
        ("CPU and Apple GPU: identical probabilities", _frac(g["identical_replies"], n)),
        ("CPU and Apple GPU: same decisions", _frac(g["same_decisions"], n)),
        ("CPU and Apple GPU: largest probability change",
         f"{g['max_abs_probability_difference']:.4f}"),
        ("Reversed order: changed choice", _frac(inv["reversed"]["flips"], n)),
        ("Each of five shuffles: changed choice", f"{min(sh)} to {max(sh)} of {n}"),
        ("Any of the six orders: changed choice", _frac(r["any_order_flip"], n)),
        ("Neutral names: changed choice", _frac(inv["names_neutral"]["flips"], n)),
        ("Names exchanged: changed choice", _frac(inv["names_swapped"]["flips"], n)),
        ("Names exchanged: followed the name", _frac(r["swapped_followed_name"], n)),
        ("Null fired: vague notices", _frac(ab["null"], ab["cases"])),
        ("Null fired: change / no-change notices",
         f"{ch['null']}/{ch['cases']} / {nc['null']}/{nc['cases']}"),
        ("One choice over all 56 ranges: options kept apart", kept),
        ("(i) Construction: right candidate offered",
         f"{ch['constructed']}/{ch['cases']} / {nc['constructed']}/{nc['cases']}"),
        ("(ii) Retention, top choices",
         f"{ch['top_right']}/{ch['cases']} / {nc['top_right']}/{nc['cases']}"),
        (f"(ii) Retention, sets of mass {r['set_mass']}",
         f"{ch['set_right']}/{ch['cases']} / {nc['set_right']}/{nc['cases']}"),
        ("Candidates those sets keep, mean of 56",
         f"{ch['mean_ranges_kept']:.1f} / {nc['mean_ranges_kept']:.1f}"),
    ]
    if b is not None:
        s = b["D_margin"]["strata"]["margin_ge_0.2"]
        a = b["A_retention"]
        extra = {
            "Any of the six orders: changed choice": [
                (r"\quad with top-two margin $\ge 0.2$\textsuperscript{\dag}",
                 _frac(s["order_changed_choice"], s["notices"]))],
            "Names exchanged: followed the name": [
                (r"\quad with top-two margin $\ge 0.2$\textsuperscript{\dag}",
                 _frac(s["followed_name"], s["notices"]))],
            f"(ii) Retention, sets of mass {r['set_mass']}": [
                (r"\quad random sets of the same size, expected\textsuperscript{\dag}",
                 f"{a['random_per_question_expected']:.0f} to "
                 f"{a['random_uniform_over_56_expected']:.0f} / --"),
                (r"\quad most frequent ranges, no reading\textsuperscript{\dag}",
                 f"{b['B_notice_blind_prior']['held_leave_one_out']}/{b['change_notices']} / --")],
        }
        out = []
        for row in rows:
            out.append(row)
            out += extra.get(row[0], [])
        rows = out
    dag = ("" if b is None else
           r" \textsuperscript{\dag}Post hoc reference points (Appendix~\ref{app:laya}).")
    lines = [
        "%% Generated by replication-package/tools/laya_table.py; do not edit by hand.",
        r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{3pt}",
        r"\caption{\cdraft{Conformance of a typed-decision reader to the L1 contract: Laya "
        r"0.4.1, zero-shot, on the " + str(n) + r" constructed notices (protocol frozen before "
        r"the first run, Appendix~\ref{app:laya}). A change is read as two choices, its first "
        r"and its last week; choices are compared by the definition chosen. Pairs give change / "
        r"no-change notices." + dag + r"}}\label{tab:layaconf}",
        r"\begin{tabular}{@{}lr@{}}", r"\toprule", r"Property & Result\\\midrule"]
    lines += [f"{a} & {b}\\\\" for a, b in rows]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--result", type=Path, default=ROOT / "results/laya_conformance.json")
    ap.add_argument("--baselines", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    base = json.loads(args.baselines.read_text()) if args.baselines else None
    args.out.write_text(table(json.loads(args.result.read_text()), base))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
