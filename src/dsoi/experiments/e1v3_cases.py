"""Phase 3 cases: fresh constructed notices, the e1v2 categories plus five new ones.

The 14 categories of e1v2 are generated by e1v2's `make`, with e1v2's truth rules
(`e1v2_notices`, data/e1v2/TRUTH_RULES.md). Five categories are new; each has two
messages from the same sender, except `constraint_change`. Their truth rules, fixed here
before any reply is collected and listed for the outside reader in data/e1v3/:
  resent             the same notice again, introduced as a resend: it states no new change,
                     so the truth is the first notice's cut (a reading that applies the cut
                     a second time, to the reduced value, misses)
  amend_size         "the reduction ... is now q%, not p%": q% of nominal capacity
  amend_extend       "the p% reduction now also covers week b + 1": weeks a to b + 1
  cancel             "the capacity reduction ... is cancelled": nominal in every week
  constraint_change  a notice that changes a constraint, not a capacity value (order
                     multiples, minimum runs, changeover notice): capacity unchanged. Under
                     Section 3 it belongs to specification review (A-SPEC); the interpreter
                     should leave capacity alone
The seed is derived from a token fixed after registration (`seed_from_token`), so the
cases cannot be chosen after the protocol is known. Cases are split once per category
into calibration and test cases by a second seeded draw.
"""

from __future__ import annotations

import hashlib
from dataclasses import asdict

import numpy as np

from dsoi.experiments.e1_notices import _fmt_range, _pct, _range
from dsoi.experiments.e1v2_notices import (
    CATEGORIES as V2_CATEGORIES,
)
from dsoi.experiments.e1v2_notices import (
    EMAIL,
    Case,
    _cap,
    _names,
    _weeks,
    load,
    save,
    snapshot,
)
from dsoi.experiments.e1v2_notices import make as make_v2

NEW_CATEGORIES = ("resent", "amend_size", "amend_extend", "cancel", "constraint_change")
CATEGORIES = V2_CATEGORIES + NEW_CATEGORIES

__all__ = ["CATEGORIES", "NEW_CATEGORIES", "Case", "generate", "glossary", "load", "make",
           "save", "seed_from_token"]


def seed_from_token(token: str) -> int:
    """A 32-bit seed from a public token fixed after registration (for example the
    registration's DOI or a block hash): the first 8 hex digits of its SHA-256."""
    if not token or token.strip().upper() == "DECIDE":
        raise ValueError("the seed token is not set: it is fixed after registration")
    return int(hashlib.sha256(token.strip().encode()).hexdigest()[:8], 16)


def make(category: str, i: int, rng) -> Case:
    if category in V2_CATEGORIES:
        return make_v2(category, i, rng)
    cid = f"{category}-{i:03d}"
    a, b = _range(rng)
    span = _fmt_range(a, b, rng)
    X, x = _names("plant:X", rng)

    def two(first: str, second: str, truth, statement, expect="change") -> Case:
        return Case(cid, category, ((EMAIL, first), (EMAIL, second)), expect, truth, statement)

    if category == "resent":
        p = _pct(rng)
        first = f"{X} capacity is reduced by {p}% for {span}."
        return two(first, f"Resending our earlier notice: {first}",
                   {"plant:X": _weeks(a, b, _cap(p))}, f"{p}% cut, sent twice")
    if category == "amend_size":
        p = _pct(rng)
        q = _pct(rng)
        while q == p:
            q = _pct(rng)
        return two(f"{X} capacity is reduced by {p}% for {span}.",
                   f"Update to our earlier notice: the reduction at {x} for {span} is now "
                   f"{q}%, not {p}%.",
                   {"plant:X": _weeks(a, b, _cap(q))}, f"{p}% cut amended to {q}%")
    if category == "amend_extend":
        p = _pct(rng)
        return two(f"{X} capacity is reduced by {p}% for {span}.",
                   f"Update to our earlier notice: the {p}% reduction at {x} now also covers "
                   f"week {b + 1}.",
                   {"plant:X": _weeks(a, b + 1, _cap(p))},
                   f"{p}% cut, extended to week {b + 1}")
    if category == "cancel":
        p = _pct(rng)
        return two(f"{X} capacity is reduced by {p}% for {span}.",
                   f"Update to our earlier notice: the capacity reduction at {x} for {span} "
                   f"is cancelled; capacity stays at normal levels.",
                   {}, f"{p}% cut, then cancelled", expect="no_change")
    if category == "constraint_change":
        text = str(rng.choice([
            f"From week {a}, {x} accepts orders only in multiples of 200 units.",
            f"{X} requires a minimum production run of 300 units per order from week {a}.",
            f"From week {a}, changeovers at {x} must be scheduled at least 48 hours ahead.",
        ]))
        return Case(cid, category, ((EMAIL, text),), "no_change", {},
                    "constraint changed, capacity not")
    raise ValueError(category)


def generate(n_calibration: int, n_test: int, seed: int) -> list[Case]:
    """All cases: n_calibration + n_test per category, split by a seeded draw per category."""
    rng = np.random.default_rng(seed)
    n = n_calibration + n_test
    cases = [make(c, i, rng) for c in CATEGORIES for i in range(n)]
    split_rng = np.random.default_rng(seed + 1)
    out = []
    for cat in CATEGORIES:
        group = [c for c in cases if c.category == cat]
        cal = {group[j].id for j in split_rng.permutation(n)[:n_calibration]}
        out += [Case(**{**asdict(c), "messages": c.messages,
                        "split": "calibration" if c.id in cal else "test"}) for c in group]
    return out


def glossary() -> str:
    """Interface factor B, snapshot withheld: the e1v2 snapshot without the lines that
    report the current state. The plant names, identifiers, units and week convention stay,
    so the arm removes the state, not the instructions."""
    return "\n".join(line for line in snapshot({}).splitlines()
                     if "currently recorded" not in line)
